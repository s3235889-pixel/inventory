const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('dist/index.html', 'utf8');
const script = html.split('<script>')[1].split('</script>')[0];
new vm.Script(script);
const core = script.slice(0, script.indexOf('let state=defaultState()'));
const context = vm.createContext({console});
vm.runInContext(core, context);
const run = expression => vm.runInContext(expression, context);
assert.equal(run("expiryDate({...defaultState().fields,made:'2028-02-28',days:3})"), '2028-03-01');
assert.equal(run("expiryDate({...defaultState().fields,made:'2028-02-28',days:3,countMode:'exclusive'})"), '2028-03-02');
assert.equal(run("expiryDate({...defaultState().fields,made:'2026-12-31',days:2})"), '2027-01-01');
assert.equal(run("expiryDate({...defaultState().fields,made:'2026-11-11',days:1})"), '2026-11-11');
assert.equal(run("validDate('2027-02-29')"), false);
assert.equal(run("validDate('2028-02-29')"), true);
assert.equal(run("expiryDate({...defaultState().fields,expiryMode:'manual',manualExpiry:'2027-01-15'})"), '2027-01-15');
assert.equal(run("formatDate('2026-11-11',{dateFormat:'roc'})"), '115/11/11');
assert.equal(run('normalize(defaultState()).paper.w'),35);
assert.throws(()=>run('normalize({...defaultState(),version:2})'));
assert.throws(()=>run('normalize({...defaultState(),paper:{w:-1,h:25}})'));
assert.throws(()=>run("normalize({...defaultState(),fields:{...defaultState().fields,made:'2027-02-29'}})"));
assert.throws(()=>run("normalize({...defaultState(),elements:[{type:'html',text:'<script>'}]})"));
assert.equal(fs.readFileSync('dist/Label-Workshop.html','utf8'),html);
assert.match(html, /@page\{size:35mm 25mm;margin:0\}/);
assert.match(html, /break-after:page/);
assert.match(html, /\.print-sheet:last-child\{break-after:auto/);
assert.doesNotMatch(html, /<script[^>]+src=/);
console.log('18 checks passed: dates, import validation, offline parity, print stylesheet.');
